package com.example.security

import java.net.URI

/**
 * Enforces strict HTTPS-only navigation and host allowlist policy for WebView.
 */
object WebViewUrlPolicy {
  const val ENTRY_URL = "https://septianfr.web.id/mail/support/login.php"
  const val ALLOWED_HOST = "septianfr.web.id"

  fun isAllowedNavigationUrl(rawUrl: String?): Boolean {
    val candidate = rawUrl?.trim() ?: return false
    if (candidate.isEmpty()) return false
    return try {
      val uri = URI(candidate)
      val scheme = uri.scheme?.lowercase() ?: return false
      val host = uri.host?.lowercase() ?: return false
      scheme == "https" && uri.userInfo == null && host == ALLOWED_HOST
    } catch (_: Exception) {
      false
    }
  }

  /**
   * Blocks cleartext HTTP, local file, and content URIs at subresource level.
   * Permits HTTPS subresources as well as inline data/blob URLs generated by the HTTPS page.
   */
  fun isAllowedSubresourceUrl(rawUrl: String?): Boolean {
    val candidate = rawUrl?.trim() ?: return false
    if (candidate.isEmpty()) return false
    return try {
      val uri = URI(candidate)
      val scheme = uri.scheme?.lowercase() ?: return false
      when (scheme) {
        "https" -> !uri.host.isNullOrBlank()
        "data", "blob" -> true
        else -> false
      }
    } catch (_: Exception) {
      false
    }
  }
}
